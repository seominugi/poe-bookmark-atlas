// src/lib/panelWidth.js
// 패널 폭과 '폭 밴드' — 넓게/좁게에 각각 이유를 만든다.
//
// 왜 밴드인가 (2026-08-13 제보: "그저 넓히기만 하니까 장단점이 없다"):
//   폭 조절을 처음 넣을 때는 최소 = 기본(384px)이라 **넓히는 한 방향**뿐이었고, 넓혀도 여백만
//   늘었다. 폭에 따라 보이는 것이 달라져야 폭을 고르는 이유가 생긴다.
//
//   narrow  (~383)  거래소 화면을 덜 가린다. 액션 행은 라벨을 버리고 아이콘만 남는다.
//   default (384~)  지금까지의 모습. 폭 예산(액션 행 실측 336/342px)이 성립하는 하한.
//   wide    (560~)  카드가 3층 → 2층으로 펴져 **한 화면에 더 많은 항목**이 보인다.
//                   조건 요약(가장 길고 가장 많이 잘리던 것)이 늘어난 폭을 전부 가져간다.
//
// ⚠ MIN_W 를 384 → 300 으로 내린 근거:
//   384 의 근거는 액션 행이 최악 폰트(system-ui·Malgun)에서 336px 을 쓰기 때문이었다
//   (test/actionRowBudget.dom.test.js 참조). narrow 밴드에서 라벨을 버리면 그 예산이 사라진다.
//   **라벨을 숨기지 않은 채로 MIN_W 만 내리면 액션 행이 즉시 줄바꿈된다** — 둘은 한 세트다.

export const MIN_W = 300
export const MAX_W = 880

/** narrow ↔ default 경계. 384 = 폭 조절 도입 전의 고정폭이자 라벨이 살아남는 하한. */
export const NARROW_MAX = 384
/**
 * default ↔ wide 경계 = 600 (하네스 실측으로 정함).
 *
 * ⚠ 이 경계의 근거는 한 번 틀렸다가 라이브 실측으로 바로잡혔다.
 *   처음엔 wide 에서 '이름 줄 + 조건 요약'을 합쳤고, 600 을 "기본폭 384 보다 두 축 모두 나아지는
 *   지점"으로 정당화했다. 그런데 사용자가 실제로 지나가는 경로는 384 가 아니라 **599 → 600** 이고,
 *   거기서 조건 요약 잘림이 **0건 → 7건**으로 튀었다(라이브 북마크 26개: 599 26/26 → 600 19/26).
 *   → 합치는 짝을 '이름 줄 + 메모'로 바꿨다(680px 실측: 이름 줄 244px vs 메모 119px — 조건 요약과
 *     폭을 나눌 짝은 좁은 쪽이어야 한다). 조건 요약은 단독 줄로 전체 폭을 갖는다. panel.css 참조.
 *   수정 후 라이브: 560·599·600·640·720·880 전 구간 **26/26 온전**, 카드 109 → 82px.
 *   이제 600 은 '넘어가면 카드만 낮아지고 잃는 게 없는' 지점이라 경계로 유효하다.
 *
 * "넓게/좁게의 장단점" — 짝을 바꾼 뒤로는 **단조롭게 좋아지는 대신 화면을 더 가리는** 구조다
 * (처음 설계했던 '구간마다 다른 성격'은 라이브 실측에서 무너졌다 — 아래가 실제 측정값이다):
 *   300~383 (narrow)  거래소를 가장 덜 가림. 대신 액션 행은 아이콘만, 조건 요약은 11/26 만 온전.
 *   384~599 (default) 384 20/26 → 560 이상 26/26. 카드 3층(109px).
 *   600~880 (wide)    26/26 온전 그대로 + 카드 2층(82px)이라 한 화면 항목이 가장 많다.
 * 즉 넓힐수록 손해 보는 축은 '거래소 화면을 얼마나 가리는가' 하나뿐이다 — 그게 선택의 축이다.
 */
export const WIDE_MIN = 600

/** 창이 좁아지면 상한도 내려간다 — 패널이 화면을 다 덮지 않게. 160px 은 거래소를 볼 최소 여지. */
export function maxPanelWidth(viewportW) {
  return Math.max(MIN_W, Math.min(MAX_W, (Number(viewportW) || 0) - 160))
}

/**
 * 저장값·드래그값을 실제 적용 가능한 폭으로.
 *
 * ⚠ '값 없음'과 '작은 값'을 구분해야 한다. 둘을 뭉뚱그리면 양쪽에서 다르게 터진다:
 *   - `Number(null)` 은 0 이라, 유한수 검사만 하면 **값 없음이 0px 요청으로** 읽혀 최소폭까지 쪼그라든다.
 *   - 그렇다고 `n > 0` 으로 막으면, 드래그가 하한을 지나쳐 **음수가 될 때 기본폭(384)으로 튀어 오른다**
 *     — 좁히려고 계속 끄는데 패널이 되레 넓어진다(라이브 드래그로 발견, 2026-08-13).
 *   그래서 '값 없음'만 따로 판정하고, 숫자는 음수든 0 이든 **진짜 요청으로 보고 하한에 눌러 담는다.**
 */
export function clampPanelWidth(w, viewportW) {
  const n = Number(w)
  const missing = w === null || w === undefined || w === '' || !Number.isFinite(n)
  const base = missing ? NARROW_MAX : n
  return Math.round(Math.max(MIN_W, Math.min(maxPanelWidth(viewportW), base)))
}

/** 폭 → 밴드. CSS 는 .ba-root[data-w="..."] 로 이 값을 받는다. */
export function widthBand(w) {
  const n = Number(w) || 0
  if (n < NARROW_MAX) return 'narrow'
  if (n >= WIDE_MIN) return 'wide'
  return 'default'
}
